"""Writes the two halves of the split between Castlevania.exe and the game DLL a player's PC builds.

A release ships no game code: Castlevania.exe holds the runtime and the host code, and on its first start builds
CastlevaniaGame.dll from the player's own default.xbe with the bundled recompiler, Clang and LLD. Linked whole, the
host's strong sub_ definitions replace the recompiled weak ones; split, each side gets forwarders instead:

  dll_glue.cpp   the runtime functions and the host's game functions, called through a table the exe hands over
  host_glue.cpp  the recompiled originals host code calls, through GetProcAddress, and the image's tables, which
                 hold addresses only (the function table's pointers are filled from the DLL when it loads)
  game.def       what the DLL exports

The symbol lists come from a whole build's objects: python split/glue.py <build dir> <generated dir> <out dir>.
"""
import hashlib
import pathlib
import re
import subprocess
import sys

NM = r"C:\Program Files\LLVM\bin\llvm-nm.exe"
RUNTIME = [  # declared in cpu/x86_ops.h; (name, return, params, call args)
    ("x86_icall", "void", "X86Context& ctx, uint8_t* base, uint32_t target", "ctx, base, target"),
    ("x86_resume", "void", "X86Context& ctx, uint8_t* base, const X86Resume& r", "ctx, base, r"),
    ("x86_kernel", "void", "X86Context& ctx, uint8_t* base, uint32_t ordinal", "ctx, base, ordinal"),
    ("x86_trap", "[[noreturn]] void", "X86Context& ctx, uint32_t va, const char* what", "ctx, va, what"),
    ("x86_priv", "void", "X86Context& ctx, uint32_t va, const char* what", "ctx, va, what"),
    ("x86_rdtsc", "uint64_t", "", ""),
    ("x86_cpuid", "void", "X86Context& ctx", "ctx"),
]


def symbols(objs, *flags):
    out = set()
    for o in objs:
        r = subprocess.run([NM, *flags, str(o)], capture_output=True, text=True)
        for line in r.stdout.splitlines():
            parts = line.split()
            if parts:
                out.add(parts[-1])
    return out


def main(build, gen, out):
    build, gen, out = pathlib.Path(build), pathlib.Path(gen), pathlib.Path(out)
    objdir = build / "CMakeFiles" / "Castlevania.dir"
    gen_objs = sorted((objdir / "generated").rglob("*.obj"))
    host_objs = sorted(o for o in objdir.rglob("*.obj") if "generated" not in o.parts)
    if not gen_objs or not host_objs:
        sys.exit("no objects: build the whole game first")
    gen_def = symbols(gen_objs, "-g", "--defined-only")
    host_def = symbols(host_objs, "-g", "--defined-only")
    host_und = symbols(host_objs, "-u")

    # the host's game functions: every strong sub_ it defines, the recompiled code calls them instead of its own
    host_subs = sorted(s for s in host_def if re.fullmatch(r"sub_[0-9A-F]{8}", s))
    # the recompiled originals host code calls
    originals = sorted(s for s in host_und & gen_def if s.startswith("__imp__sub_"))
    other = sorted(s for s in host_und & gen_def if not s.startswith("__imp__sub_") and not s.startswith("?X86"))
    if other:
        sys.exit("host code uses generated symbols the split does not carry: " + ", ".join(other))

    mapping = (gen / "x86_func_mapping.cpp").read_text()
    consts = dict(re.findall(r"const uint32_t (X86\w+) = (0x[0-9A-F]+u);", mapping))
    conts = re.search(r"X86Continuations\[\] = \{(.*?)\};", mapping, re.S).group(1)
    count = len(re.findall(r"^\t\{0x", mapping, re.M))

    out.mkdir(parents=True, exist_ok=True)
    stamp_src = "|".join(host_subs + originals) + str(count) + conts
    stamp = hashlib.sha1(stamp_src.encode()).hexdigest()[:16]

    n_rt = len(RUNTIME)
    dll = [
        "// generated by split/glue.py: the game DLL's calls into Castlevania.exe",
        '#include "cpu/x86_ops.h"',
        "",
        "using CvFn = void (*)();",
        f"static CvFn g_host[{n_rt + len(host_subs)}];",
        "",
        "// MSVC's floating point marker and the type_info vtable RTTI descriptors point at; neither is read",
        'extern "C" int _fltused = 0x9875;',
        'extern const void* const cv_type_info_vft[1] __asm__("??_7type_info@@6B@") = {nullptr};',
        "",
        f'extern "C" const char* CvStamp() {{ return "{stamp}"; }}',
        'extern "C" void XbeImageInit(const CvFn* host, int count) {',
        f"    for (int i = 0; i < count && i < {n_rt + len(host_subs)}; i++) g_host[i] = host[i];",
        "}",
        "",
    ]
    for i, (name, ret, params, args) in enumerate(RUNTIME):
        call = f"reinterpret_cast<decltype(&{name})>(g_host[{i}])({args})"
        body = f"return {call};" if ret == "uint64_t" else f"{call};"
        if "noreturn" in ret:
            body = f"{call};\n    __builtin_unreachable();"
        dll.append(f"{ret} {name}({params}) {{\n    {body}\n}}")
    dll.append("")
    for i, s in enumerate(host_subs):
        dll.append(f"X86_FUNC({s}) {{ reinterpret_cast<X86Func*>(g_host[{n_rt + i}])(ctx, base); }}")
    (out / "dll_glue.cpp").write_text("\n".join(dll) + "\n")

    host = [
        "// generated by split/glue.py: Castlevania.exe's side of the game DLL",
        "#ifndef WIN32_LEAN_AND_MEAN",
        "#define WIN32_LEAN_AND_MEAN",
        "#endif",
        "#ifndef NOMINMAX",
        "#define NOMINMAX",
        "#endif",
        "#include <windows.h>",
        "",
        "#include <cstring>",
        "",
        '#include "cpu/x86_ops.h"',
        "",
        "// the image's addresses, the same for every copy of this release",
    ]
    for k in ["X86CodeBase", "X86CodeEnd", "X86ImageBase", "X86ImageEnd", "X86EntryPoint", "X86KernelThunk"]:
        host.append(f"extern const uint32_t {k} = {consts[k]};")
    host += [
        f"extern const uint32_t X86Continuations[] = {{{conts.strip()}}};",
        "",
        "// the function table: guest addresses and the DLL's functions, filled when it loads",
        "// (writable, under the name the runtime declares it const by)",
        f'X86FuncMapping cv_mappings[{count + 1}] __asm__("?X86FuncMappings@@3QBUX86FuncMapping@@B");',
        "",
        f'extern "C" const char kCvStamp[] = "{stamp}";',
        "",
        "using CvFn = void (*)();",
        f"static CvFn g_dll[{max(len(originals), 1)}];",
        "",
    ]
    for i, s in enumerate(originals):
        host.append(f"X86_FUNC({s}) {{ reinterpret_cast<X86Func*>(g_dll[{i}])(ctx, base); }}")
    host += [""] + [f"X86_EXTERN_FUNC({s});" for s in host_subs] + [""]
    host.append("static const CvFn kHost[] = {")
    for name, *_ in RUNTIME:
        host.append(f"    reinterpret_cast<CvFn>(&{name}),")
    for s in host_subs:
        host.append(f"    reinterpret_cast<CvFn>(&{s}),")
    host.append("};")
    host += [
        "",
        "// the DLL loaded: hands it the host's functions, takes its table and originals; false when it is not this",
        "// release's",
        "bool CvWire(HMODULE dll) {",
        '    auto stamp = reinterpret_cast<const char* (*)()>(GetProcAddress(dll, "CvStamp"));',
        '    auto init = reinterpret_cast<void (*)(const CvFn*, int)>(GetProcAddress(dll, "XbeImageInit"));',
        '    auto maps = reinterpret_cast<const X86FuncMapping*>(GetProcAddress(dll, "CvMappings"));',
        "    if (!stamp || !init || !maps || std::strcmp(stamp(), kCvStamp) != 0) return false;",
        f"    static const char* const kOriginals[] = {{{', '.join(chr(34) + 'cv_orig_' + s[len('__imp__'):] + chr(34) for s in originals) or 'nullptr'}}};",
        f"    for (int i = 0; i < {len(originals)}; i++)",
        "        if (!(g_dll[i] = reinterpret_cast<CvFn>(GetProcAddress(dll, kOriginals[i])))) return false;",
        "    std::memcpy(cv_mappings, maps, sizeof(cv_mappings));",
        "    init(kHost, int(sizeof(kHost) / sizeof(kHost[0])));",
        "    return true;",
        "}",
    ]
    (out / "host_glue.cpp").write_text("\n".join(host) + "\n")

    exports = ["LIBRARY CastlevaniaGame", "EXPORTS", "    XbeImageInit", "    CvStamp",
               "    CvMappings = ?X86FuncMappings@@3QBUX86FuncMapping@@B DATA"]
    exports += [f"    cv_orig_{s[len('__imp__'):]} = {s}" for s in originals]
    (out / "game.def").write_text("\n".join(exports) + "\n")
    (out / "stamp.txt").write_text(stamp + "\n")
    print(f"glue: {len(host_subs)} host functions, {len(originals)} originals, {count} mapped, stamp {stamp}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
